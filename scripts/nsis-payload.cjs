'use strict';

const fs = require('node:fs');
const path = require('node:path');

function escapeNsisLiteral(value) {
  // '$' starts NSIS runtime variable expansion even inside quoted strings.
  // Windows forbids double quotes in path components, but escape them anyway
  // for a clearer failure mode if a synthetic path is supplied by a test.
  return String(value).replace(/\$/g, () => '$$').replace(/"/g, '$"');
}

function toNsisPath(value, workingDir) {
  // Generate paths relative to makensis' working directory (installer/),
  // and use Windows separators. This avoids NSIS wildcard/glob resolution
  // and absolute forward-slash path quirks.
  return path.relative(path.resolve(workingDir), path.resolve(value)).replace(/[\\/]/g, '\\');
}

function listFilesRecursively(rootDir) {
  const root = path.resolve(rootDir);
  if (!fs.existsSync(root)) throw new Error(`Packaged app directory does not exist: ${root}`);
  if (!fs.statSync(root).isDirectory()) throw new Error(`Packaged app path is not a directory: ${root}`);

  const files = [];
  function visit(directory) {
    const entries = fs.readdirSync(directory, { withFileTypes: true })
      .sort((a, b) => a.name.localeCompare(b.name, 'en'));
    for (const entry of entries) {
      const fullPath = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) {
        const target = fs.statSync(fullPath);
        if (target.isDirectory()) visit(fullPath);
        else if (target.isFile()) files.push(fullPath);
        else throw new Error(`Unsupported symbolic link in packaged app: ${fullPath}`);
      } else if (entry.isDirectory()) {
        visit(fullPath);
      } else if (entry.isFile()) {
        files.push(fullPath);
      }
    }
  }
  visit(root);
  files.sort((a, b) => path.relative(root, a).replace(/\\/g, '/').localeCompare(path.relative(root, b).replace(/\\/g, '/'), 'en'));
  return { root, files };
}

function generatePayloadInclude(appOutDir, nsisWorkingDir) {
  const { root, files } = listFilesRecursively(appOutDir);
  const workingDir = path.resolve(nsisWorkingDir || path.dirname(root));
  if (files.length === 0) throw new Error(`Packaged app directory contains no files: ${root}`);

  const lines = [
    '; Generated by scripts/build-installer.cjs. Do not edit manually.',
    '; Explicit source file list avoids NSIS wildcard path resolution issues.',
    '!macro InstallPayload'
  ];
  let activeOutputDir = null;
  for (const file of files) {
    const relative = path.relative(root, file);
    const relativeDir = path.dirname(relative);
    const normalizedDir = relativeDir === '.' ? '' : relativeDir.split(path.sep).join('\\');
    if (normalizedDir !== activeOutputDir) {
      const destination = normalizedDir ? `$INSTDIR\\${escapeNsisLiteral(normalizedDir)}` : '$INSTDIR';
      lines.push(`  SetOutPath "${destination}"`);
      activeOutputDir = normalizedDir;
    }
    lines.push(`  File "${escapeNsisLiteral(toNsisPath(file, workingDir))}"`);
  }
  lines.push('!macroend', '');
  return lines.join('\r\n');
}

module.exports = { escapeNsisLiteral, listFilesRecursively, generatePayloadInclude };
